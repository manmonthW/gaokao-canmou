def main():
    conn = psycopg2.connect(**DB)
    cur = conn.cursor()

    # 清空旧 GDP,用图片精确值重写
    cur.execute("UPDATE cities SET gdp=NULL, gdp_year=NULL, note=NULL")
    print(f"已清空旧 GDP")

    updated = 0
    not_found = []
    for city, gdp in GDP_2025.items():
        cur.execute("SELECT 1 FROM cities WHERE city=%s", (city,))
        if cur.fetchone():
            cur.execute(
                "UPDATE cities SET gdp=%s, gdp_year=2025, note='2025城市GDP年报(图片)' WHERE city=%s",
                (gdp, city),
            )
            updated += 1
        else:
            not_found.append(city)

    conn.commit()

    # 民族后缀重复城市: 从主城市复制
    cur.execute("""
        UPDATE cities c1 SET gdp=c2.gdp, gdp_year=c2.gdp_year, note=c2.note||'(从主城复制)'
        FROM cities c2
        WHERE c1.gdp IS NULL AND c2.gdp IS NOT NULL AND (
            (c1.city LIKE '伊犁哈萨克%' AND c2.city='伊犁')
            OR (c1.city LIKE '凉山彝族%' AND c2.city='凉山')
            OR (c1.city LIKE '博尔塔拉蒙古%' AND c2.city='博尔塔拉')
            OR (c1.city LIKE '巴音郭楞蒙古%' AND c2.city='巴音郭楞')
            OR (c1.city LIKE '延边朝鲜族%' AND c2.city='延边')
            OR (c1.city LIKE '恩施土家族苗族%' AND c2.city='恩施')
            OR (c1.city LIKE '楚雄彝族%' AND c2.city='楚雄')
            OR (c1.city LIKE '红河哈尼族彝族%' AND c2.city='红河')
            OR (c1.city LIKE '湘西土家族苗族%' AND c2.city='湘西')
            OR (c1.city LIKE '黔南布依族苗族%' AND c2.city='黔南')
            OR (c1.city LIKE '黔东南苗族侗族%' AND c2.city='黔东南')
            OR (c1.city LIKE '大理白族%' AND c2.city='大理')
            OR (c1.city LIKE '甘南藏族%' AND c2.city='甘南')
            OR (c1.city LIKE '昌吉回族%' AND c2.city='昌吉')
            OR (c1.city LIKE '陵水黎族自治%' AND (c2.city='陵水' OR c2.city='三亚'))
        )
    """)
    copied = cur.rowcount
    conn.commit()

    # 统计
    cur.execute("SELECT count(*) FROM cities WHERE gdp IS NOT NULL")
    total_with = cur.fetchone()[0]
    cur.execute("SELECT count(*) FROM cities")
    total_all = cur.fetchone()[0]

    print(f"\n=== 更新完成 ===")
    print(f"  直接匹配: {updated} 城")
    print(f"  主城复制: {copied} 城(民族后缀)")
    print(f"  总覆盖率: {total_with}/{total_all} ({100*total_with//total_all}%)")

    if not_found:
        print(f"  未匹配({len(not_found)}): {not_found[:20]}")

    # Top 20
    print("\n=== 2025 GDP Top 20 ===")
    cur.execute(
        "SELECT row_number() OVER (ORDER BY gdp DESC) 排名, city, province, tier, gdp "
        "FROM cities WHERE gdp IS NOT NULL ORDER BY gdp DESC LIMIT 20"
    )
    for r in cur.fetchall():
        print(f"  {r[0]:>3}. {r[1]:8s} | {r[2]:6s} | {r[3]:6s} | {r[4]:>12,.1f}亿")

    # 大连确认
    cur.execute("SELECT city,gdp,gdp_year FROM cities WHERE city='大连'")
    r = cur.fetchone()
    print(f"\n>>> 大连 2025 GDP: {r[1]:,.1f} 亿元 (年份:{r[2]})")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
