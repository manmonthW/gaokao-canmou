def main():
    conn = psycopg2.connect(**DB)
    cur = conn.cursor()

    # 先清空旧 GDP（之前只有6个锚点）
    cur.execute("UPDATE cities SET gdp=NULL, gdp_year=NULL, note=NULL")
    print(f"已清空全部 GDP")

    updated = 0
    not_found = []
    for city, gdp in GDP_DATA.items():
        cur.execute("SELECT 1 FROM cities WHERE city=%s", (city,))
        if cur.fetchone():
            cur.execute(
                "UPDATE cities SET gdp=%s, gdp_year=2024, note='2024城市GDP年鉴(图片)' WHERE city=%s",
                (gdp, city),
            )
            updated += 1
        else:
            not_found.append(city)

    conn.commit()

    # 统计
    cur.execute("SELECT count(*) FROM cities WHERE gdp IS NOT NULL")
    total_with = cur.fetchone()[0]
    cur.execute("SELECT count(*) FROM cities")
    total_all = cur.fetchone()[0]

    print(f"\n更新完成:")
    print(f"  匹配更新: {updated} 城")
    print(f"  cities 含 GDP: {total_with} / {total_all}")
    if not_found:
        print(f"  未匹配({len(not_found)}): {not_found[:20]}")

    # 展示 Top 15
    print("\n=== GDP Top 15 ===")
    cur.execute(
        "SELECT city, province, tier, gdp FROM cities WHERE gdp IS NOT NULL ORDER BY gdp DESC LIMIT 15"
    )
    for r in cur.fetchall():
        print(f"  {r[0]:8s} | {r[1]:6s} | {r[2]:6s} | {r[3]:,.1f}亿")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
